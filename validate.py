"""Checks the interior-reimagine-workflow repo and builds the offline bundle.

Usage, from the repo root:
    python3 validate.py            run every check
    python3 validate.py --bundle   rebuild start-here-bundle.md, then run every check

No dependencies. Exit code 0 means every check passed.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
REPO = "kiianlow/interior-reimagine-workflow"
RAW = "https://raw.githubusercontent.com/%s/main/" % REPO
BUNDLE = "start-here-bundle.md"
UPPERCASE_OK = {"START-HERE.md", "README.md", "CHANGELOG.md", "STYLE-INDEX.md", "CLAUDE.md"}
MAX_START_HERE_WORDS = 2500
MAX_PROMPT_BLOCK_WORDS = 70

HEADINGS = ["Prompt block", "Mood", "Palette", "Furniture", "Textiles and window treatments",
            "Lighting", "Greenery and decor", "REVAMP finishes", "Avoid", "Marketing fit"]
ROOM_LINES = ["Living", "Dining", "Bedroom", "Study", "Kitchen", "Bathroom", "Balcony"]
FINISH_LINES = ["Walls", "Flooring", "Ceiling lights", "Carpentry", "Kitchen", "Bathroom"]

# Words that would leak fixed finishes or room furniture into every prompt.
PROMPT_BLOCK_BANNED = re.compile(
    r"\b(walls?|floors?|flooring|ceilings?|cabinet\w*|carpentry|built-ins?|integrated|limewash|"
    r"plaster|microcement|tiles?|backsplash|countertops?|pendants?|curtains?|blinds?|sofas?|beds?|"
    r"tables?|desks?|wardrobes?|rugs?|chairs?|storage|shelving|shelves|surfaces?)\b", re.I)
HYPE = re.compile(r"\b(stunning|amazing|breathtaking|incredible|revolutionary|world-class|jaw-dropping)\b", re.I)

errors = []


def fail(msg):
    errors.append(msg)


def read(name):
    with open(os.path.join(ROOT, name), encoding="utf-8") as fh:
        return fh.read()


def repo_files():
    out = []
    for name in sorted(os.listdir(ROOT)):
        if name.startswith("."):
            continue
        path = os.path.join(ROOT, name)
        if os.path.isdir(path):
            fail("Folder found: %s. Keep every file in the root." % name)
            continue
        out.append(name)
    return out


def style_files(files):
    return sorted(f for f in files if re.fullmatch(r"style-\d\d-[a-z0-9-]+\.md", f))


def section(text, heading):
    m = re.search(r"^## %s\n(.*?)(?=^## |\Z)" % re.escape(heading), text, re.S | re.M)
    return m.group(1).strip() if m else None


def build_bundle(files):
    parts = [
        "# Interior Reimagine Workflow: Offline Bundle",
        "",
        "Generated by validate.py from START-HERE.md and every style file. Do not edit by hand.",
        "",
        "Use this file when the GitHub links will not open. It holds the complete engine and every style. "
        "Do not fetch any links. When START-HERE says to open a style file, use the matching style below.",
        "",
        "---",
        "",
        read("START-HERE.md").strip(),
    ]
    for f in style_files(files):
        parts += ["", "---", "", read(f).strip()]
    return "\n".join(parts) + "\n"


def check_names(files):
    seen = {}
    for f in files:
        if f in UPPERCASE_OK:
            pass
        elif not re.fullmatch(r"[a-z0-9-]+\.(md|py)", f):
            fail("Bad file name: %s. Use lowercase letters, digits and hyphens." % f)
        key = f.lower()
        if key in seen:
            fail("Duplicate name ignoring case: %s and %s" % (seen[key], f))
        seen[key] = f
    for f in ("START-HERE.md", "kickoff.md", "STYLE-INDEX.md", "CHANGELOG.md", "README.md", BUNDLE):
        if f not in files:
            fail("Missing file: %s" % f)


def check_links(files):
    sh = read("START-HERE.md")
    for url in re.findall(r"https?://[^\s|)`\"]+", sh):
        if not url.startswith(RAW):
            fail("START-HERE has a non-raw link: %s" % url)
            continue
        target = url[len(RAW):]
        if "/" in target:
            fail("START-HERE links into a folder: %s" % url)
        elif target not in files:
            fail("START-HERE links to a missing file: %s" % target)
    for f in files:
        if not f.endswith(".md") or f == BUNDLE:
            continue
        for target in re.findall(re.escape(RAW) + r"([^\s|)`\"<]+)", read(f)):
            if "/" in target or target not in files:
                fail("%s links to a missing or folder path: %s" % (f, target))
    if RAW + "START-HERE.md" not in read("kickoff.md"):
        fail("kickoff.md does not contain the START-HERE raw link.")


def check_style_lists(files):
    sh = read("START-HERE.md")
    s9 = section(sh, "9. Style library") or ""
    list_sh = re.findall(r"^\| (\d\d) \| ([^|]+?) \| https", s9, re.M)
    list_idx = re.findall(r"^\| (\d\d) \| ([^|]+?) \|", read("STYLE-INDEX.md"), re.M)
    line = [l for l in read("kickoff.md").splitlines() if re.match(r"^01 \S", l)]
    list_kick = [(x.strip()[:2], x.strip()[3:]) for x in line[0].split(",")] if line else []
    if not list_sh:
        fail("No style table found in START-HERE section 9.")
    if list_sh != list_idx:
        fail("Style list differs between START-HERE section 9 and STYLE-INDEX.md.")
    if list_sh != list_kick:
        fail("Style list differs between START-HERE section 9 and the kickoff.md Style numbers line.")
    numbers = [n for n, _ in list_sh]
    found = style_files(files)
    for num, name in list_sh:
        match = [f for f in found if f.startswith("style-%s-" % num)]
        if len(match) != 1:
            fail("Style %s needs exactly one file, found %d." % (num, len(match)))
            continue
        if RAW + match[0] not in s9:
            fail("Style %s file %s is not linked in START-HERE section 9." % (num, match[0]))
        title = read(match[0]).splitlines()[0]
        if title != "# Style %s: %s" % (num, name):
            fail("%s title is '%s', expected '# Style %s: %s'." % (match[0], title, num, name))
    for f in found:
        if f[6:8] not in numbers:
            fail("%s is not in the style list." % f)


def check_style_files(files):
    for f in style_files(files) + ["style-template.md"]:
        t = read(f)
        heads = re.findall(r"^## (.+)$", t, re.M)
        if heads != HEADINGS:
            fail("%s headings are %s, expected %s." % (f, heads, HEADINGS))
            continue
        if f == "style-template.md":
            continue
        block = section(t, "Prompt block")
        words = len(block.split())
        if words >= MAX_PROMPT_BLOCK_WORDS:
            fail("%s Prompt block has %d words. Keep it under %d." % (f, words, MAX_PROMPT_BLOCK_WORDS))
        leaks = sorted(set(w.lower() for w in PROMPT_BLOCK_BANNED.findall(block)))
        if leaks:
            fail("%s Prompt block names furniture or fixed finishes: %s. Move them to Furniture or REVAMP finishes." % (f, ", ".join(leaks)))
        rooms = re.findall(r"^- ([A-Za-z ]+): \S", section(t, "Furniture"), re.M)
        if rooms != ROOM_LINES:
            fail("%s Furniture lines are %s, expected %s." % (f, rooms, ROOM_LINES))
        fins = re.findall(r"^- ([A-Za-z ]+): \S", section(t, "REVAMP finishes"), re.M)
        if fins != FINISH_LINES:
            fail("%s REVAMP finishes lines are %s, expected %s." % (f, fins, FINISH_LINES))


def check_text(files):
    for f in files:
        t = read(f)
        if "\u2014" in t or "\u2013" in t:
            fail("%s contains an em or en dash." % f)
        if f != "validate.py" and HYPE.search(t):
            fail("%s contains a hype word: %s" % (f, HYPE.search(t).group(0)))
        if not f.endswith(".md"):
            continue
        in_code = False
        for i, line in enumerate(t.splitlines(), 1):
            if line.lstrip().startswith("```"):
                in_code = not in_code
                continue
            if ";" in line and not in_code:
                fail("%s line %d has a semicolon outside a code block." % (f, i))


def check_versions():
    sh = read("START-HERE.md")
    m = re.search(r"^Version (\d+\.\d+(?:\.\d+)?)$", sh, re.M)
    if not m:
        fail("START-HERE has no 'Version X.Y' line.")
        return
    v = m.group(1)
    if 'Engine %s loaded' % v not in sh:
        fail("START-HERE handshake line does not say 'Engine %s loaded'." % v)
    if "Engine: %s" % v not in sh:
        fail("START-HERE run summary does not say 'Engine: %s'." % v)
    top = re.search(r"^## (\S+)", read("CHANGELOG.md"), re.M)
    if not top or top.group(1) != v:
        fail("CHANGELOG top entry is %s, START-HERE is %s." % (top.group(1) if top else "missing", v))
    if "Current engine: version %s." % v not in read("README.md"):
        fail("README 'Current engine' line does not match version %s." % v)
    if os.path.exists(os.path.join(ROOT, "CLAUDE.md")) and "at repo version %s." % v not in read("CLAUDE.md"):
        fail("CLAUDE.md 'Last updated' line does not match version %s." % v)
    n = len(sh.split())
    if n > MAX_START_HERE_WORDS:
        fail("START-HERE has %d words. Keep it under %d." % (n, MAX_START_HERE_WORDS))
    nums = [int(x) for x in re.findall(r"^## (\d+)\. ", sh, re.M)]
    if nums != list(range(1, len(nums) + 1)):
        fail("START-HERE section numbers are not 1 to N in order: %s" % nums)
    return v, n


def main():
    files = repo_files()
    if "--bundle" in sys.argv:
        with open(os.path.join(ROOT, BUNDLE), "w", encoding="utf-8") as fh:
            fh.write(build_bundle(files))
        print("Wrote %s" % BUNDLE)
        files = repo_files()
    check_names(files)
    check_links(files)
    check_style_lists(files)
    check_style_files(files)
    check_text(files)
    info = check_versions()
    if BUNDLE in files and read(BUNDLE) != build_bundle(files):
        fail("%s is out of date. Run: python3 validate.py --bundle" % BUNDLE)

    styles = style_files(files)
    blocks = [len(section(read(f), "Prompt block").split()) for f in styles]
    print("Files: %d, all in root" % len(files))
    if info:
        print("START-HERE: version %s, %d words" % info)
    if blocks:
        print("Prompt blocks: %d to %d words" % (min(blocks), max(blocks)))
    if errors:
        print("\nFAIL: %d problem(s)" % len(errors))
        for e in errors:
            print("- " + e)
        sys.exit(1)
    print("PASS: every check passed")


if __name__ == "__main__":
    main()
